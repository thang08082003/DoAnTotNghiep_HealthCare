final healthAlertRepositoryProvider = Provider<HealthAlertRepository>((ref) {
  return HealthAlertRepository();
});

final healthConnectServiceProvider = Provider<GoogleFitService>((ref) {
  return GoogleFitService();
});

final localNotificationsProvider = Provider<FlutterLocalNotificationsPlugin>((
  ref,
) {
  return FlutterLocalNotificationsPlugin();
});

final healthMonitoringServiceProvider = Provider<HealthMonitoringService>((
  ref,
) {
  return HealthMonitoringService(
    alertRepository: ref.watch(healthAlertRepositoryProvider),
    healthService: ref.watch(healthConnectServiceProvider),
    notifications: ref.watch(localNotificationsProvider),
  );
});

/// Start health monitoring using existing PassiveListener
Future<void> startHealthMonitoring(String userId) async {
  // PassiveListener already running - just enable AI checks
  final prefs = await SharedPreferences.getInstance();
  await prefs.setBool('ai_monitoring_enabled_$userId', true);
  await prefs.setInt(
    'last_ai_check_$userId',
    DateTime.now().millisecondsSinceEpoch,
  );

  // Run immediate check
  await runImmediateHealthCheck(userId);
}

/// Stop health monitoring
Future<void> stopHealthMonitoring() async {
  final prefs = await SharedPreferences.getInstance();
  final keys = prefs.getKeys().where(
    (k) => k.startsWith('ai_monitoring_enabled_'),
  );
  for (final key in keys) {
    await prefs.remove(key);
  }
}

/// Run immediate health check
Future<Map<String, dynamic>> runImmediateHealthCheck(String userId) async {
  final container = ProviderContainer();
  final service = container.read(healthMonitoringServiceProvider);

  try {
    final result = await service.monitorUser(userId);
    return result;
  } catch (e) {
    print('[HealthMonitoring] Check failed: $e');
    rethrow;
  } finally {
    container.dispose();
  }
}

/// Check if should run AI monitoring (every 6 hours)
Future<bool> shouldRunAIMonitoring(String userId) async {
  final prefs = await SharedPreferences.getInstance();
  if (!(prefs.getBool('ai_monitoring_enabled_$userId') ?? false)) return false;

  final lastCheck = prefs.getInt('last_ai_check_$userId') ?? 0;
  final now = DateTime.now().millisecondsSinceEpoch;

  if (now - lastCheck >= 6 * 60 * 60 * 1000) {
    await prefs.setInt('last_ai_check_$userId', now);
    return true;
  }
  return false;
}

/// Provider for doctor's patient alerts
final doctorPatientAlertsProvider = FutureProvider.family
    .autoDispose<List<HealthAlert>, String>((ref, doctorId) async {
      final followRepo = FollowRequestRepository();
      final alertRepo = HealthAlertRepository();

      // Get list of patients followed by this doctor
      final patientIds = await followRepo.getAcceptedPatientIdsForDoctor(
        doctorId,
      );

      if (patientIds.isEmpty) return [];

      // Get recent abnormal alerts from these patients
      return await alertRepo.getRecentAbnormalAlertsForPatients(
        patientIds,
        hoursBack: 24,
        limit: 10,
      );
    });

