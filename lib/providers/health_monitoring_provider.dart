/// Send notification to patient
Future<void> _sendPatientNotification({
  required String userId,
  required AlertLevel alertLevel,
  required String message,
}) async {
  try {
    final String title;
    switch (alertLevel) {
      case AlertLevel.normal:
        title = '✅ Kết quả phân tích sức khỏe';
        break;
      case AlertLevel.warning:
        title = '⚠️ Cảnh báo sức khỏe';
        break;
      case AlertLevel.danger:
        title = '🚨 Cảnh báo sức khỏe khẩn cấp';
        break;
    }

    await FlutterLocalNotificationsPlugin().show(
      DateTime.now().millisecondsSinceEpoch.remainder(100000),
      title,
      message,
      NotificationDetails(
        android: AndroidNotificationDetails(
          'health_monitoring',
          'Theo dõi sức khỏe',
          channelDescription: 'Thông báo về tình trạng sức khỏe',
          importance: Importance.high,
          priority: Priority.high,
          icon: '@drawable/ic_stat_notify',
        ),
      ),
    );
  } catch (e) {
    print('[HealthMonitoring] Failed to send notification: $e');
  }
}
